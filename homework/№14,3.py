ch = '123456789ABC'  # создаем строку со всеми цифрами 13сс, кроме 0, так как эта сс наименьшая в задании
# не берём 0, потому что во втором слагаемом число начинается с х, а писать 0 в начале нет смысла
for x in ch:  # перебираем все цифры из 13 системы счисления
    # подставляем х в числа, переводим их сразу в 10сс и находим значение выражения
    s = int(f'9{x}AB', 13) + int(f'{x}46C', 16) - int(f'B7{x}', 15)
    if s % 14 == 0:  # если значение выражения кратно 14
        print(s // 14)  # выводим частное от деления на 14
        break  # Останавливаем перебор, т.к. ищем наименьшее