l = list()  # Будем сюда добавлять списки вида [количество нулей при этом x, x]
for x in range(1, 2031):
    a = 7 ** 170 + 7 ** 100 - x

    cnt = 0
    while a > 0:
        if (a % 7) == 0:
            cnt += 1
        a //= 7
    l.append([cnt, x])  # Добавляем

print(max(l))  # Получим максимальное количество нулей и x, при котором оно достигается