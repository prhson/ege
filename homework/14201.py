# Перебираем x и проверяем условие для записи числа Значение арифметического выражения 3100 – x, где x – целое положительное число, не превышающее 2030, записали в троичной системе счисления.
#
# Определите наибольшее значение x, при котором количество нулей в троичной записи числа, являющегося значением данного арифметического выражения, максимально.
#
# В ответе запишите число в десятичной системе счисления.
for x in range(2030, 0, -1):
    n = 3**(100)-x
    count = 0
    m = n
    while m > 0:
        if m % 3 == 0:
            count += 1
        m //= 3
    if count == 5:
        print(x)
        break