res = set()  # множество, в котором будем хранить уникальные значения выражения
# перебираем х от 10, т.к. во втором числе есть цифра 9, а значит, что его минимальная сс это 10
# перебираем x до 67, т.к. в первом числе он может принимать значения от 0 до 66 включительно
for x in range(10, 67):
    for y in range(x):  # перебираем y до х, т.к. y не может быть больше сс своего числа
        # расписываем оба числа как сумму цифр числа умноженную на сс числа в степени своей позиции в числе справа, чтобы перевести их в 10 сс
        f = (7 * 67 ** 4) + (3 * 67 ** 3) + (x * 67 ** 2) + (1 * 67 ** 1) + (y * 67 ** 0)
        s = (4 * x ** 3) + (9 * x ** 2) + (y * x ** 1) + (6 * x ** 0)
        res.add(f + s)  # добавляем сумму чисел в множество
print(len(res)) # выводим ответ - длину множества